def currency_name(code: str, lang: str) -> str:
    names = CURRENCY_NAMES.get(code)
    return names[_I[lang]] if names else code


class Translator:
    def __init__(self, lang: str):
        self.i = _I.get(lang, 0)

    def t(self, key: str, **kw) -> str:
        entry = S.get(key)
        if entry is None:
            return key
        text = entry[self.i] or entry[0]
        return text.format(**kw) if kw else text
